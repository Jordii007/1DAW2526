public class Ud5Ej9 {
    public static void main(String[] args){
        //Entorno
        int i, e;
        //Algoritmo
        //While
        System.out.println("Con WHILE");
        i=0;
        while (i<=9){
            i=i+1;
            System.out.println(i);
        }

        //Do
        System.out.println("Con Do");
        e=0;
        do{
            e=e+1;
            System.out.println(e);
        }while(e<=9);

    }
}
